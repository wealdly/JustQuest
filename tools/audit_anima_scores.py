# Audit every curated anima power score against the spell's real name and description.
#
#   python tools/audit_anima_scores.py [--csv-dir DIR] [--out FILE]
#
# Exists because a score can be wrong in three ways that all fail silently in play:
#   1. The ID is right but the SCORE disagrees with what the power actually does.
#   2. The ID is missing entirely, so the power falls to the rarity fallback and may land
#      below the floor — which is how "Obleron Venom x2" (294610, absent) scored 46 and was
#      handed back, while 294609 and 294611 sat in the table at 65 and 54.
#   3. Only one mode has an entry, so the other mode silently drops to the fallback.
#
# Rank variants ("X", "X x2", "X x3") are the main trap: they are consecutive spell IDs and it
# is easy to curate two of the three.
#
# Required CSVs in --csv-dir (pull from https://wago.tools): SpellName, Spell.
import argparse, csv, io, os, re, sys
from collections import defaultdict

csv.field_size_limit(10 ** 7)
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def newest(csv_dir, prefix):
    import glob
    hits = sorted(glob.glob(os.path.join(csv_dir, prefix + ".*.csv")) +
                  glob.glob(os.path.join(csv_dir, prefix + ".csv")))
    return hits[-1] if hits else None


def tables(src):
    out = {}
    for t in ("BLOCKED", "SCORES_NORMAL", "SCORES_FARMING"):
        m = re.search(r"AnimaPowerDB\.%s = \{(.*?)\n\}" % t, src, re.S)
        out[t] = {}
        for line in m.group(1).split("\n"):
            e = re.match(r'\s*\[(\d+)\]\s*=\s*\{\s*name\s*=\s*"([^"]*)"(.*)$', line)
            if not e:
                continue
            pr = re.search(r"priority\s*=\s*(\d+)", e.group(3))
            out[t][int(e.group(1))] = (e.group(2), int(pr.group(1)) if pr else None)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv-dir", default=r"r:\WOW\Interface\AddOns\JustAC\Documentation\wow_spell_csv")
    ap.add_argument("--out", default=os.path.join(ROOT, "Documentation", "anima_score_audit.md"))
    args = ap.parse_args()

    name_csv, spell_csv = newest(args.csv_dir, "SpellName"), newest(args.csv_dir, "Spell")
    if not name_csv:
        sys.exit(f"need SpellName.*.csv in {args.csv_dir}")

    src = io.open(os.path.join(ROOT, "Database", "AnimaPowerDB.lua"), encoding="utf-8").read()
    tb = tables(src)
    curated = set(tb["SCORES_NORMAL"]) | set(tb["SCORES_FARMING"]) | set(tb["BLOCKED"])

    names = {}
    for r in csv.DictReader(io.open(name_csv, encoding="utf-8", errors="replace", newline="")):
        try:
            names[int(r["ID"])] = r["Name_lang"]
        except (ValueError, TypeError):
            pass

    desc = {}
    if spell_csv:
        for r in csv.DictReader(io.open(spell_csv, encoding="utf-8", errors="replace", newline="")):
            try:
                i = int(r["ID"])
            except (ValueError, TypeError):
                continue
            if i in curated or True:
                d = (r.get("Description_lang") or "").strip()
                if d:
                    desc[i] = d

    # --- rank families: "Foo", "Foo x2", "Foo x3" ---------------------------------
    family = defaultdict(dict)
    for sid, nm in names.items():
        m = re.match(r"^(.*?) x(\d)$", nm)
        if m:
            family[m.group(1)][int(m.group(2))] = sid
        elif nm:
            family[nm].setdefault(1, sid)

    missing_ranks = []
    for base, ranks in family.items():
        present = {r: s for r, s in ranks.items() if s in curated}
        if present and len(present) != len(ranks):
            gaps = sorted(set(ranks) - set(present))
            missing_ranks.append((base, {r: ranks[r] for r in gaps}, present))

    mode_only = [sid for sid in curated
                 if (sid in tb["SCORES_NORMAL"]) != (sid in tb["SCORES_FARMING"])
                 and sid not in tb["BLOCKED"]]

    mismatched = []
    for sid in sorted(curated):
        cur = (tb["SCORES_NORMAL"].get(sid) or tb["SCORES_FARMING"].get(sid) or tb["BLOCKED"].get(sid))[0]
        live = names.get(sid, "")
        if live and cur.lower() not in live.lower() and live.lower() not in cur.lower():
            mismatched.append((sid, cur, live))

    lines = ["# Anima power score audit", "",
             f"{len(curated)} curated IDs — {len(tb['SCORES_NORMAL'])} normal, "
             f"{len(tb['SCORES_FARMING'])} farming, {len(tb['BLOCKED'])} blocked.", "",
             "Generated by `tools/audit_anima_scores.py`. Review the score against the "
             "description; the engine only ever sees the number.", ""]

    lines += ["## Missing rank variants", "",
              "Rank variants are consecutive spell IDs. A gap here means that rank falls to the "
              "rarity fallback and can land below the mode floor even though its siblings are "
              "curated high.", ""]
    if missing_ranks:
        lines += ["| power | missing | have |", "|---|---|---|"]
        for base, gaps, present in sorted(missing_ranks):
            g = ", ".join(f"x{r}=`{s}`" for r, s in sorted(gaps.items()))
            h = ", ".join(f"x{r}=`{s}`" for r, s in sorted(present.items()))
            lines.append(f"| {base} | {g} | {h} |")
    else:
        lines.append("_none_")

    lines += ["", "## Curated in only one mode", "",
              "The other mode drops straight to the rarity fallback rather than using the "
              "score we already have.", ""]
    if mode_only:
        lines += ["| id | name | normal | farming |", "|---|---|---|---|"]
        for sid in sorted(mode_only):
            n = tb["SCORES_NORMAL"].get(sid)
            f = tb["SCORES_FARMING"].get(sid)
            lines.append(f"| `{sid}` | {(n or f)[0]} | {n[1] if n else '—'} | {f[1] if f else '—'} |")
    else:
        lines.append("_none_")

    # --- unblocked siblings of known traps ----------------------------------------
    # The highest-stakes gap in the whole file. The game may offer ANY id carrying a power, and
    # a hand-written blocklist only ever caught the id that happened to be seen in play. Missing
    # one of these costs the run, not one weaker pick — 12 were found this way.
    label_csv = newest(args.csv_dir, "SpellLabel")
    roster = set()
    if label_csv:
        for r in csv.DictReader(io.open(label_csv, encoding="utf-8", errors="replace", newline="")):
            if r.get("LabelID") == "630":
                try:
                    roster.add(int(r["SpellID"]))
                except (ValueError, TypeError):
                    pass
    by_name = defaultdict(list)
    for sid in roster:
        nm = names.get(sid)
        if nm:
            by_name[nm].append(sid)

    orphan_traps = []
    for sid, (cur_name, _) in sorted(tb["BLOCKED"].items()):
        nm = names.get(sid) or cur_name
        sibs = [s for s in sorted(by_name.get(nm, [])) if s not in tb["BLOCKED"]]
        if sibs:
            orphan_traps.append((nm, sorted(s for s, (n, _) in tb["BLOCKED"].items()
                                            if (names.get(s) or n) == nm), sibs))
    seen = set()
    orphan_traps = [t for t in orphan_traps if not (t[0] in seen or seen.add(t[0]))]

    lines += ["", "## Unblocked sibling IDs of blocked traps", "",
              "**Highest priority.** The game may offer any id that carries a power; blocking "
              "only the id you happened to see leaves the others live. Missing one costs the "
              "run, not one weaker pick.", ""]
    if orphan_traps:
        lines += ["| trap | blocked | NOT blocked |", "|---|---|---|"]
        for nm, have, sibs in orphan_traps:
            lines.append(f"| {nm} | {', '.join(f'`{i}`' for i in have)} | "
                         f"{', '.join(f'`{i}`' for i in sibs)} |")
    else:
        lines.append("_none — every id sharing a blocked power's name is blocked_")

    lines += ["", "## Name disagrees with the live spell", ""]
    if mismatched:
        lines += ["| id | curated | actual |", "|---|---|---|"]
        for sid, cur, live in mismatched:
            lines.append(f"| `{sid}` | {cur} | {live} |")
    else:
        lines.append("_none_")

    lines += ["", "## Every entry, for eyeball review", "",
              "| id | name | normal | farming | description |", "|---|---|---|---|---|"]
    for sid in sorted(curated):
        n = tb["SCORES_NORMAL"].get(sid)
        f = tb["SCORES_FARMING"].get(sid)
        b = tb["BLOCKED"].get(sid)
        nm = names.get(sid) or (n or f or b)[0]
        d = (desc.get(sid, "") or "").replace("\n", " ").replace("|", "\\|")[:160]
        score_n = "**BLOCKED**" if b else (n[1] if n else "—")
        score_f = "**BLOCKED**" if b else (f[1] if f else "—")
        lines.append(f"| `{sid}` | {nm} | {score_n} | {score_f} | {d} |")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    io.open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    print(f"curated IDs           : {len(curated)}")
    print(f"missing rank variants : {len(missing_ranks)}   <- these fall to the rarity fallback")
    print(f"curated in one mode   : {len(mode_only)}")
    print(f"name mismatches       : {len(mismatched)}")
    print(f"descriptions resolved : {sum(1 for s in curated if s in desc)}/{len(curated)}")
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
