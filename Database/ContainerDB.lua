-- ============================================================
-- ⚠️ NEW IN v3.3.0: USER-DRIVEN WHITELIST SYSTEM
-- ============================================================
-- This database is now OPTIONAL and serves as a fallback only.
-- 
-- **Primary System**: User-driven whitelist
--   - Users add containers they want automated via slash commands
--   - No pre-populated list - users build their own
--   - Command: /jq container add <itemID>
--   - Unknown containers prompt user to add them
--
-- **This Database**: Optional fallback for convenience
--   - Enable: /jq config → Containers → "Use Database Fallback"
--   - When enabled, provides a starting point for automation
--   - Users can still customize (add/remove specific containers)
--   - Users who prefer full control can disable this entirely
--
-- **Why this change?**
--   1. Simpler maintenance - no massive database to update
--   2. User control - players decide what gets automated
--   3. Safety - users test containers before adding to whitelist
--   4. Flexibility - works across all expansions without database updates
--
-- **Migration Path**:
--   - Existing users: Database fallback enabled by default (no change in behavior)
--   - New users: Can choose to enable database or build custom list from scratch
--   - Power users: Disable database, use only personal whitelist
--
